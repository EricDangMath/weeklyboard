import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { occursInWeek, hasWeeklyRecurrence, applyCalendarEdit } from '../../src/calendar-occurrences.mjs';
import { parseCalendar } from '../calendar-feed.js';

test('new recurring segments respect both bounds and client reconciliation preserves the original and exception', () => {
  const original = { id: 1, title: 'Old', week_key: '2026-W45', repeat_rule: 'weekly', layer: 'once', ends_before_week: '2026-W49' };
  const replacement = { ...original, id: 2, title: 'New', week_key: '2026-W49', starts_on_week: '2026-W49', ends_before_week: '2027-W02' };
  assert.equal(hasWeeklyRecurrence(original), true);
  assert.equal(hasWeeklyRecurrence({ ...original, layer: 'actual' }), false);
  assert.equal(hasWeeklyRecurrence({ week_key: null }), true);
  assert.equal(occursInWeek(replacement, '2026-W48'), false);
  assert.equal(occursInWeek(replacement, '2026-W49'), true);
  assert.equal(occursInWeek(replacement, '2027-W01'), true);
  assert.equal(occursInWeek(replacement, '2027-W02'), false);
  const source = [{ ...original, ends_before_week: null }, { id: 3, title: 'Untouched' }];
  const result = applyCalendarEdit(source, { event: original, replacement }, 1);
  assert.equal(source[0].ends_before_week, null);
  assert.deepEqual(result.find((item) => item.id === 1), original);
  assert.equal(result.find((item) => item.id === 3).title, 'Untouched');
  assert.equal(applyCalendarEdit(result, { event: original, replacement }, 1).length, 3);
});

test('week-only and future edits preserve history, task statistics, exclusions, cutoff, restart, backup and ICS', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'weeklyboard-recurring-edits-'));
  const env = { ...process.env, DB_FILE: join(directory, 'test.sqlite'), PORT: '0', DEBUG_MODE: 'true', JWT_SECRET: randomBytes(32).toString('hex'), PUBLIC_CALENDAR_BASE_URL: '' };
  let child, exited;
  const start = async () => {
    child = spawn(process.execPath, [resolve('server/index.js')], { env, stdio: ['ignore', 'pipe', 'pipe'] });
    exited = once(child, 'exit');
    const port = await new Promise((resolvePort, reject) => {
      let output = '';
      const timer = setTimeout(() => reject(new Error(`API startup timeout: ${output}`)), 10000);
      child.stdout.on('data', (chunk) => { output += chunk; const match = output.match(/weeklyboard api listening (\d+)/); if (match) { clearTimeout(timer); resolvePort(match[1]); } });
      child.stderr.on('data', (chunk) => { output += chunk; });
      child.once('exit', () => { clearTimeout(timer); reject(new Error(output)); });
    });
    return `http://127.0.0.1:${port}/api`;
  };
  try {
    let base = await start();
    const session = await (await fetch(`${base}/auth/debug`)).json();
    const request = async (path, method = 'GET', body, status = 200, token = session.token) => {
      const response = await fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
      assert.equal(response.status, status, `${method} ${path}`);
      return response.json().catch(() => null);
    };
    const task = await request(`/projects/${session.demo.projectId}/tasks`, 'POST', { title: 'Scoped edit task', estimate_minutes: 60 }, 201);
    const original = await request('/calendar/events', 'POST', { title: task.title, task_id: task.id, day: '周一', start_minute: 540, end_minute: 600, layer: 'once', category: 'study', week_key: '2026-W45', repeat: true }, 201);
    const edit = (id, scope, week) => `/calendar/events/${id}?scope=${scope}&week_key=${week}`;
    await request(`/calendar/events/${original.id}?scope=week`, 'PATCH', { title: 'Bad range' }, 400);
    await request(edit(original.id, 'invalid', '2026-W47'), 'PATCH', { title: 'Bad scope' }, 400);
    await request(edit(original.id, 'week', '2026-W47'), 'PATCH', { end_minute: 500 }, 400);
    const other = await request('/auth/register', 'POST', { email: 'edit-other@example.test', password: 'test-password-123' }, 201);
    await request(edit(original.id, 'future', '2026-W47'), 'PATCH', { title: 'Other user' }, 404, other.token);
    await request(`/calendar/events/${original.id}?scope=future&week_key=2027-W02`, 'DELETE');
    for (const week of ['2026-W48', '2026-W50']) await request(`/calendar/events/${original.id}?scope=week&week_key=${week}`, 'DELETE');
    const patch = { title: 'This week only', day: '周二', start_minute: 600, end_minute: 690, description: 'One-off note', category: 'sport' };
    const changed = await request(edit(original.id, 'week', '2026-W47'), 'PATCH', patch);
    assert.equal(changed.event.title, original.title);
    assert.equal(changed.event.day, '周一');
    assert.equal(changed.event.ends_before_week, '2027-W02');
    assert.equal(changed.replacement.repeat_rule, null);
    assert.equal(changed.replacement.week_key, '2026-W47');
    assert.equal(changed.replacement.task_id, task.id);
    assert.equal(changed.replacement.category, 'sport');
    assert.equal(changed.replacement.description, patch.description);
    await request(edit(original.id, 'week', '2026-W47'), 'PATCH', patch, 409);
    assert.equal((await request('/calendar')).length, 2);
    const minutes = async (week) => (await request(`/pomodoro?week_key=${week}`)).rows.find((row) => row.task_id === task.id).daily.reduce((sum, day) => sum + day.planned_minutes, 0);
    const before = await minutes('2026-W46');
    assert.equal(before, 60);
    assert.equal(await minutes('2026-W47'), 90);
    const future = await request(edit(original.id, 'future', '2026-W49'), 'PATCH', { title: 'Future schedule', day: '周四', start_minute: 660, end_minute: 750, category: 'work', description: 'New routine' });
    assert.equal(future.event.ends_before_week, '2026-W49');
    assert.equal(future.replacement.starts_on_week, '2026-W49');
    assert.equal(future.replacement.ends_before_week, '2027-W02');
    assert.equal(future.replacement.repeat_rule, 'weekly');
    assert.deepEqual(JSON.parse(future.replacement.excluded_weeks), ['2026-W50']);
    assert.equal(await minutes('2026-W46'), 60);
    assert.equal(await minutes('2026-W47'), 90);
    assert.equal(await minutes('2026-W48'), 0);
    assert.equal(await minutes('2026-W49'), 90);
    assert.equal(await minutes('2026-W50'), 0);
    assert.equal(await minutes('2027-W02'), 0);
    await request(edit(original.id, 'future', '2026-W49'), 'PATCH', { title: 'Stale retry' }, 409);
    const publication = await request('/calendar/publish', 'PUT', { title: 'Scoped edits', timezone: 'America/New_York', layers: ['once'], include_deadlines: false });
    const feed = await (await fetch(base + publication.path)).text();
    assert.match(feed, /EXDATE;TZID=America\/New_York:20261210T110000/);
    const imported = await parseCalendar(feed, { timezone: 'America/New_York', now: '2026-11-01T00:00:00Z' });
    const newSeries = imported.blocks.filter((item) => item.title === 'Future schedule');
    assert.ok(newSeries.some((item) => item.week_key === '2026-W49'));
    assert.ok(newSeries.every((item) => item.week_key >= '2026-W49' && item.week_key < '2027-W02' && item.week_key !== '2026-W50'));
    assert.ok(imported.blocks.some((item) => item.title === 'This week only' && item.week_key === '2026-W47'));
    assert.ok(imported.blocks.filter((item) => item.title === original.title).every((item) => item.week_key < '2026-W49' && !['2026-W47', '2026-W48'].includes(item.week_key)));
    const backup = await request('/backup');
    child.kill(); await exited;
    base = await start();
    await request('/backup/restore', 'POST', { backup });
    const rows = await request('/calendar');
    assert.equal(rows.find((item) => item.id === future.replacement.id).starts_on_week, '2026-W49');
    assert.equal(await minutes('2026-W46'), 60);
    assert.equal(await minutes('2026-W49'), 90);
    assert.equal(await minutes('2026-W48'), 0);
    const stop = await request(edit(future.replacement.id, 'future', '2026-W51'), 'PATCH', { repeat: false, title: 'Last occurrence' });
    assert.equal(stop.replacement.repeat_rule, null);
    assert.equal(await minutes('2026-W51'), 90);
    assert.equal(await minutes('2026-W52'), 0);
  } finally {
    child?.kill(); if (exited) await exited;
    await rm(directory, { recursive: true, force: true });
  }
});
